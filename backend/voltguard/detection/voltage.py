"""Stage 2: voltage locator (SDD 5.2, FR-PS-02; depends on AS-3, AS-7, AS-8).

A hidden load draws current that the meters do not record. On its own phase and branch
that current pulls every meter's voltage down by I * R(common path to the tap), so the
unexplained drop grows along the line up to the tap and stays flat beyond it; the tap's
own meter drops further through its service cable.

Each meter's voltage is taken relative to the transformer (its meter's voltage, or the
median of meters on the same phase), which cancels changes in the transformer voltage and
overall load. Two signals:

* residual (level): measured relative voltage minus what the load flow expects from metered
  loads - works for theft running since day one, needs network parameters (AS-8);
* change: the drop after the zone's gap start compared with before.

Within each phase and branch the locator fits drop_j = -a * min(R_j, R_k) for every
candidate tap node k and keeps the best fit.

R0 tests this only on voltages generated by the load-flow model, because the open datasets
hold kWh only; whether it works on TNB meters depends on AS-3.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from voltguard.detection.balance import BalanceResult, network_for
from voltguard.detection.zone_input import SLOTS, ZoneInput
from voltguard.network import V_NOMINAL, solve


@dataclass
class VoltageResult:
    available: bool
    method: str                          # residual | change | none
    confidence: str                      # high | low
    residual_v: np.ndarray               # (n,) unexplained voltage (negative = drop), NaN when unknown
    change_v: np.ndarray                 # (n,) change after gap start, NaN when unknown
    signal_v: np.ndarray                 # (n,) the signal the locator used
    tap_distance_m: np.ndarray           # (n,) distance from the estimated tap on the premise's phase/branch
    group_drop_v: np.ndarray             # (n,) fitted drop at the tap for the premise's group
    groups: list[dict] = field(default_factory=list)  # per phase/branch fit, for the voltage strip
    notes: list[str] = field(default_factory=list)


def _relative_voltage(z: ZoneInput) -> np.ndarray:
    v = z.voltage
    if z.tx_voltage is not None:
        return v - z.tx_voltage[None, :]
    phases = z.phase_index()
    rel = np.full_like(v, np.nan)
    for p in set(phases.tolist()):
        members = phases == p
        with np.errstate(all="ignore"):
            ref = np.nanmedian(v[members], axis=0)
        rel[members] = v[members] - ref[None, :]
    return rel


def _fit_group(signal: np.ndarray, r: np.ndarray) -> tuple[int, float, float]:
    """Best tap position (index into the group) and fitted drop a*R_k; returns (k, drop_v, sse)."""
    best = (0, 0.0, np.inf)
    for k in range(len(r)):
        x = np.minimum(r, r[k])
        denom = float((x**2).sum())
        if denom <= 0:
            continue
        a = max(-float((signal * x).sum()) / denom, 0.0)
        sse = float(((signal + a * x) ** 2).sum())
        if sse < best[2] - 1e-12:
            best = (k, a * r[k], sse)
    return best


def locate(z: ZoneInput, bal: BalanceResult, filled: np.ndarray, conv_est: np.ndarray, cfg: dict) -> VoltageResult:
    vc = cfg["voltage"]
    n = z.n
    nan = np.full(n, np.nan)
    if not z.has_voltage:
        return VoltageResult(False, "none", "low", nan, nan, nan, nan, np.zeros(n), notes=["No voltage data (AS-3): stage skipped."])

    rel = _relative_voltage(z)
    start = bal.gap_start_index
    window_days = int(vc["window_days"])
    t_end = z.T
    t_start = (start * SLOTS) if start is not None else max(0, t_end - window_days * SLOTS)
    window = slice(t_start, t_end)

    # Weight intervals by how much energy is unexplained: hidden load and voltage drop move together.
    weights = np.ones(z.T)
    if bal.slot_gap_kwh is not None:
        weights = np.clip(bal.slot_gap_kwh, 0, None) + 1e-3
    w = weights[window]

    residual = nan.copy()
    method = "change"
    notes: list[str] = []
    net = network_for(z) if z.has_topology else None
    if net is not None and z.loss_params is not None:
        v_tx = z.tx_voltage if z.tx_voltage is not None else np.full(z.T, V_NOMINAL + 6.0)
        v_tx = np.where(np.isfinite(v_tx), v_tx, np.nanmedian(v_tx))
        expected = solve(net, (filled + conv_est)[:, window] * 2.0, v_tx[window]).prem_voltage - v_tx[window][None, :]
        diff = rel[:, window] - expected
        ok = np.isfinite(diff)
        residual = np.where(ok.any(axis=1), (np.where(ok, diff, 0) * w).sum(axis=1) / np.maximum((ok * w).sum(axis=1), 1e-9), np.nan)
        method = "residual"
    else:
        notes.append("Network parameters missing (AS-8): change signal only.")

    change = nan.copy()
    if start is not None and start >= 3:
        before = slice(max(0, (start - 14) * SLOTS), start * SLOTS)
        has = np.isfinite(rel[:, window]).any(axis=1) & np.isfinite(rel[:, before]).any(axis=1)
        if has.any():
            change[has] = np.nanmean(rel[has][:, window], axis=1) - np.nanmean(rel[has][:, before], axis=1)
    signal = residual if method == "residual" else change
    if not np.isfinite(signal).any():
        return VoltageResult(True, "none", "low", residual, change, signal, nan, np.zeros(n),
                             notes=notes + ["No visible change and no network parameters: locator cannot run."])

    # Groups: phase and branch from the network model, or street order only (AS-7 fallback).
    confidence = "high"
    if z.has_topology:
        branches = np.array(z.premises["feeder_branch"].to_list())
        phases = z.phase_index()
        keys = [f"{b}/{'ABC'[p]}" for b, p in zip(branches, phases)]
        position = np.array(z.premises["distance_m"].to_list(), dtype=float)
        r_path = net.path_resistance()[net.prem_node] if net is not None else position
    else:
        confidence = "low"
        notes.append("Phase or branch not recorded (AS-7): street order and phase-blind medians, low confidence.")
        keys = ["all"] * n
        position = np.array(z.premises["street_seq"].to_list(), dtype=float)
        r_path = position
    keys = np.array(keys)

    tap_distance = nan.copy()
    group_drop = np.zeros(n)
    groups = []
    for key in sorted(set(keys.tolist())):
        members = np.where((keys == key) & np.isfinite(signal))[0]
        if len(members) < 2:
            continue
        k, drop, _ = _fit_group(signal[members], r_path[members])
        tap_pos = position[members][k]
        all_members = np.where(keys == key)[0]
        tap_distance[all_members] = np.abs(position[all_members] - tap_pos)
        group_drop[all_members] = drop
        order = np.argsort(position[members])
        groups.append({
            "group": key, "tap_position": float(tap_pos), "fitted_drop_v": round(float(drop), 3),
            "premises": [z.premise_ids[members[j]] for j in order],
            "positions": [float(position[members[j]]) for j in order],
            "signal_v": [round(float(signal[members[j]]), 3) for j in order],
        })
    if not z.smart.all():
        notes.append("Monthly-read meters have no voltage; they are placed by their position relative to the fitted tap.")
    return VoltageResult(True, method, confidence, residual, change, signal, tap_distance, group_drop, groups, notes)

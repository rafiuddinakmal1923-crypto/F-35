"""Test accounts: one per role and region from config/demo.yaml, plus the pipeline service account.

Passwords come from DEMO_PASSWORDS in .env (generated by `make.ps1 setup`, never committed).
A user missing from DEMO_PASSWORDS gets a fresh strong password, printed once.
"""

from __future__ import annotations

import psycopg

from voltguard import auth, config


def demo_users() -> list[dict]:
    users = list(config.demo_config().get("users", []))
    users.append({"user_id": "pipeline", "role": "pipeline", "region": "*"})
    return users


def seed_users(conn: psycopg.Connection, passwords: dict[str, str] | None = None) -> dict[str, str]:
    """Create or update the test accounts (owner connection). Returns user -> password actually set."""
    passwords = dict(passwords if passwords is not None else auth.demo_passwords())
    used: dict[str, str] = {}
    for user in demo_users():
        uid = user["user_id"]
        password = passwords.get(uid) or auth.generate_password()
        used[uid] = password
        conn.execute(
            """INSERT INTO app_user (user_id, role, region, team, display_name, password_hash)
               VALUES (%s, %s, %s, %s, %s, %s)
               ON CONFLICT (user_id) DO UPDATE SET role = EXCLUDED.role, region = EXCLUDED.region, team = EXCLUDED.team,
                 display_name = EXCLUDED.display_name, password_hash = EXCLUDED.password_hash, active = true""",
            (uid, user["role"], user["region"], user.get("team"), user.get("display_name") or uid.replace(".", " ").title(),
             auth.hash_password(password)))
    return used

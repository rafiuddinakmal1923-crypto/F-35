"""Generate TRACEABILITY.md: every SRS requirement mapped to the code and tests that cite it.

Requirement IDs come from VoltGuard_SRS.md. Code references are IDs (or ID ranges such as
"FR-ZD-01 to FR-ZD-06" / "FR-PS-03 to 05") in docstrings and comments; test references are
test names such as `test_FR_ZD_02_small_tap_flagged`.
"""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ID = r"(?:FR-[A-Z]{2}-\d{2}|NFR-\d{2})"
RANGE = re.compile(r"((?:FR-[A-Z]{2}|NFR))-(\d{2})\s*(?:to|–|-)\s*(?:(?:FR-[A-Z]{2}|NFR)-)?(\d{2})\b")
TEST_NAME = re.compile(r"def (test_((?:FR_[A-Z]{2}_\d{2}|NFR_\d{2})(?:_(?:FR_[A-Z]{2}_\d{2}|NFR_\d{2}))*)_?\w*)\(")


def requirements() -> list[tuple[str, str, str]]:
    rows = []
    for line in (ROOT / "VoltGuard_SRS.md").read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 3 and re.fullmatch(ID, cells[0]):
            if cells[0].startswith("FR"):
                rows.append((cells[0], cells[2], cells[1]))
            else:
                rows.append((cells[0], "NFR", f"{cells[1]}: {cells[2]}"))
    return rows


def expand(text: str) -> set[str]:
    found = set(re.findall(ID, text))
    for prefix, a, b in RANGE.findall(text):
        if int(b) > int(a) and int(b) - int(a) < 15:
            found.update(f"{prefix}-{n:02d}" for n in range(int(a), int(b) + 1))
    return found


def main() -> int:
    code_refs: dict[str, set[str]] = defaultdict(set)
    test_refs: dict[str, set[str]] = defaultdict(set)
    sources = list((ROOT / "backend" / "voltguard").rglob("*.py")) + list((ROOT / "scripts").glob("*.py"))
    web = ROOT / "web" / "src"
    if web.exists():
        sources += [p for p in web.rglob("*") if p.suffix in (".ts", ".tsx", ".js", ".jsx")]
    for path in sources:
        if path.name == "traceability.py":
            continue
        rel = path.relative_to(ROOT).as_posix()
        for rid in expand(path.read_text(encoding="utf-8", errors="ignore")):
            code_refs[rid].add(rel)
    for path in (ROOT / "backend" / "tests").rglob("test_*.py"):
        rel = path.relative_to(ROOT).as_posix()
        for match in TEST_NAME.finditer(path.read_text(encoding="utf-8")):
            for part in re.findall(r"FR_[A-Z]{2}_\d{2}|NFR_\d{2}", match.group(2)):
                test_refs[part.replace("_", "-")].add(f"{rel}::{match.group(1)}")

    lines = [
        "# Traceability",
        "",
        "Generated by `scripts/traceability.py` (run by `make.ps1 handoff`). Do not edit by hand.",
        "Status: **tested** = at least one test named after the requirement; **code** = implemented and",
        "cited in code but no dedicated test yet; **open** = not implemented yet.",
        "",
        "| ID | Priority | Requirement | Status | Code | Tests |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    counts: dict[str, int] = defaultdict(int)
    for rid, priority, text in requirements():
        tests, code = sorted(test_refs.get(rid, [])), sorted(code_refs.get(rid, []))
        status = "tested" if tests else ("code" if code else "open")
        counts[(priority, status)] += 1
        short = text if len(text) <= 90 else text[:87] + "..."
        code_cell = "<br>".join("`" + c + "`" for c in code[:4]) + (f" (+{len(code) - 4})" if len(code) > 4 else "")
        test_cell = "<br>".join("`" + t.split("::")[1] + "`" for t in tests[:4]) + (f" (+{len(tests) - 4})" if len(tests) > 4 else "")
        lines.append(f"| {rid} | {priority} | {short} | {status} | {code_cell} | {test_cell} |")
    summary = ["", "## Summary", "", "| Priority | tested | code | open |", "| --- | --- | --- | --- |"]
    for priority in ("Must", "Should", "Could", "NFR"):
        summary.append(f"| {priority} | {counts[(priority, 'tested')]} | {counts[(priority, 'code')]} | {counts[(priority, 'open')]} |")
    lines[6:6] = summary + ["", "## Requirements", ""]
    (ROOT / "TRACEABILITY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote TRACEABILITY.md ({sum(counts.values())} requirements)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
